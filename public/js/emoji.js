  function recent() {
    try {
      const r = JSON.parse(localStorage.getItem(RECENT_KEY) || '[]');
      return Array.isArray(r) ? r.filter((x) => typeof x === 'string' && x.length <= 16).slice(0, 24) : [];
    } catch { return []; }
  }
  function remember(e) {
    const list = [e, ...recent().filter((x) => x !== e)].slice(0, 24);
    try { localStorage.setItem(RECENT_KEY, JSON.stringify(list)); } catch { /* storage blocked */ }
  }

  /** fills `host` with tabs + a grid. onPick(emoji) runs on click. */
  function build(host, onPick) {
    const { h } = Ui;
    host.textContent = '';
    const grid = h('div', { class: 'emoji-grid', role: 'listbox', 'aria-label': 'Emoji' });
    const tabs = h('div', { class: 'emoji-tabs', role: 'tablist' });
    const show = (name) => {
      const list = name === 'Recent' ? recent() : (SETS.find((s) => s[0] === name) || SETS[0])[1];
      grid.textContent = '';
      if (!list.length) grid.append(h('p', { class: 'emoji-none', text: 'Emojis you use show up here.' }));
      for (const e of list) {
        grid.append(h('button', { type: 'button', class: 'emoji', text: e, 'aria-label': e, on: { click: () => { remember(e); onPick(e); } } }));
      }
      tabs.querySelectorAll('button').forEach((b) => b.classList.toggle('is-active', b.dataset.set === name));
      grid.scrollTop = 0;
    };
    const names = ['Recent', ...SETS.map((s) => s[0])];
    for (const n of names) tabs.append(h('button', { type: 'button', role: 'tab', text: n, 'data-set': n, on: { click: () => show(n) } }));
    host.append(tabs, grid);
    show(recent().length ? 'Recent' : 'Smileys');
  }

  return { build, SETS };
